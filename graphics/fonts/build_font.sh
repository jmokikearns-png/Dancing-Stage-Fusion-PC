#!/usr/bin/env bash
# Build the DSF PC theme's "Common Normal" StepMania font from the token
# heading font (Exo 2 Bold): metrics with fontTools, glyph sheet with
# Remotion (2x, "(res 512x512)"), then the .ini.
#   build_font.sh THEME_DIR
set -euo pipefail
G=$(cd "$(dirname "$0")/.." && pwd)
THEME=$1
PY=${PY:-/home/user/work/tools/venv-disc/bin/python}
BROWSER=${BROWSER:-/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell}
FONT=$G/node_modules/@fontsource/exo-2/files/exo-2-latin-700-normal.woff2
SIZE=24 BASELINE=24 CELL=32
"$PY" -I "$G/fonts/font_metrics.py" "$FONT" $SIZE "$G/fonts/exo2-700-24.json"
mkdir -p "$THEME/Fonts"
(cd "$G" && npx remotion still src/index.ts FontCommonNormal "$THEME/Fonts/Common Normal 16x16 (res 512x512).png" \
	--browser-executable="$BROWSER" --image-format=png --log=error)
"$PY" -I - "$G/fonts/exo2-700-24.json" "$THEME/Fonts/Common Normal.ini" $BASELINE <<'PY'
import json, sys
m = json.load(open(sys.argv[1]))
baseline = int(sys.argv[3])
top = baseline - int(round(m['capHeight']))
lines = ['# Generated by port/graphics/fonts/build_font.sh: Exo 2 Bold (SIL OFL 1.1),',
         '# the DSF PC heading font, rendered with Remotion from the design tokens.',
         '[main]',
         'AdvanceExtraPixels=2',
         'DrawExtraPixelsLeft=2',
         'DrawExtraPixelsRight=2',
         'Top=%d' % top,
         'Baseline=%d' % baseline,
         'LineSpacing=28']
lines += ['%d=%d' % (i, w) for i, w in enumerate(m['widths'])]
open(sys.argv[2], 'w', newline='\r\n').write('\n'.join(lines) + '\n')
print(sys.argv[2], 'Top', top)
PY
